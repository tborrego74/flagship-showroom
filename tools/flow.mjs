import { chromium } from 'playwright';
const S = process.argv[2];
const [W, H] = (process.argv[3] || '1440x900').split('x').map(Number);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: W, height: H } });
page.on('console', (m) => { if (m.type() === 'error') console.log('[error]', m.text().slice(0, 300)); });
page.on('pageerror', (e) => console.log('[pageerror]', e.message.slice(0, 400)));
const mode = () => page.evaluate(() => window.__showroom.mode);
const until = async (want, ms = 150000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if ((await mode()) === want) return true; await page.waitForTimeout(500); } console.log('timeout waiting for', want, 'at', await mode()); return false; };
await page.goto('http://localhost:4173/?skip', { waitUntil: 'load' });
await until('desk'); await page.waitForTimeout(2500);
await page.screenshot({ path: `${S}/f1-desk.png` });
await page.evaluate(() => window.__showroom.enter(window.__showroom.laptops[1]));
await until('inside'); await page.waitForTimeout(5000);
await page.screenshot({ path: `${S}/f2-inside.png` });
await page.evaluate(() => window.__showroom.enter(window.__showroom.laptops[2], 'phone'));
await page.waitForTimeout(1500); await until('inside'); await page.waitForTimeout(5000);
await page.screenshot({ path: `${S}/f3-phone.png` });
await page.keyboard.press('Escape'); await page.evaluate(() => window.__showroom.exit());
await until('desk'); await page.waitForTimeout(2500);
await page.screenshot({ path: `${S}/f4-back.png` });
console.log('frames in viewer:', await page.evaluate(() => document.querySelectorAll('#viewer iframe').length), 'hash', await page.evaluate(() => location.hash));
await browser.close();
